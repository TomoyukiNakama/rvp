#!/usr/bin/env python3
"""Regenerates licenses/third-party.toml: every crate linked into rvp (normal
dependencies for this platform) with its licence expression and the licence
texts shipped in the crate. The app embeds the file (`src/about.rs`).

Run after changing dependencies:  python3 scripts/gen-licenses.py
`--check` exits non-zero when the file is out of date.
"""

import hashlib
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "licenses", "third-party.toml")
FALLBACK_DIR = os.path.join(ROOT, "licenses", "texts")
LICENSE_PREFIXES = ("LICENSE", "LICENCE", "COPYING", "COPYRIGHT", "UNLICENSE", "OFL", "UFL")


def run(*args):
    return subprocess.run(args, cwd=ROOT, check=True, capture_output=True, text=True).stdout


def linked_crates():
    """(name, version) of crates actually compiled into the binary."""
    out = run("cargo", "tree", "-e", "normal", "--prefix", "none", "--format", "{p}")
    crates = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[1].startswith("v"):
            crates.add((parts[0], parts[1][1:]))
    return crates


def license_files(crate_dir):
    found = []
    for base, dirs, files in os.walk(crate_dir):
        dirs[:] = [d for d in dirs if d in ("fonts", "license", "licenses", "LICENSES")]
        for f in sorted(files):
            if f.upper().startswith(LICENSE_PREFIXES) or (base != crate_dir and f.endswith(".txt")):
                found.append(os.path.join(base, f))
    return sorted(found)


def fallback_texts(expr):
    """Standard texts for crates that don't ship their licence files."""
    texts = []
    for spdx in ("Apache-2.0", "MIT", "WTFPL"):
        if spdx in expr:
            with open(os.path.join(FALLBACK_DIR, spdx + ".txt"), encoding="utf-8") as f:
                texts.append((spdx + " (標準テキスト)", f.read()))
            break  # one text is enough for an `OR` expression
    return texts


def toml_str(s):
    return json.dumps(s, ensure_ascii=False)


def toml_multiline(s):
    # Literal multi-line string; texts never contain ''' in practice.
    assert "'''" not in s
    return "'''\n" + s + "'''"


def generate():
    meta = json.loads(run("cargo", "metadata", "--format-version", "1", "--locked"))
    wanted = linked_crates()
    root = meta["resolve"]["root"]
    rows, texts = [], {}
    for p in meta["packages"]:
        if p["id"] == root or (p["name"], p["version"]) not in wanted:
            continue
        crate_dir = os.path.dirname(p["manifest_path"])
        entries = []
        for path in license_files(crate_dir):
            with open(path, encoding="utf-8", errors="replace") as f:
                entries.append((os.path.relpath(path, crate_dir), f.read()))
        if not entries:
            entries = fallback_texts(p["license"] or "")
        ids = []
        for name, body in entries:
            body = body.replace("\r\n", "\n").rstrip() + "\n"
            key = hashlib.sha1(body.encode()).hexdigest()[:12]
            texts[key] = body
            ids.append((name, key))
        rows.append((p, ids))
    rows.sort(key=lambda r: (r[0]["name"].lower(), r[0]["version"]))

    out = ["# Generated by scripts/gen-licenses.py — do not edit.\n"]
    for p, ids in rows:
        out.append("[[crate]]")
        out.append(f"name = {toml_str(p['name'])}")
        out.append(f"version = {toml_str(p['version'])}")
        out.append(f"license = {toml_str(p['license'] or '不明')}")
        out.append(f"repository = {toml_str(p['repository'] or '')}")
        out.append("texts = [" + ", ".join(f"[{toml_str(n)}, {toml_str(k)}]" for n, k in ids) + "]")
        out.append("")
    out.append("[texts]")
    for key in sorted(texts):
        out.append(f"{key} = {toml_multiline(texts[key])}")
    return "\n".join(out) + "\n"


def main():
    content = generate()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != content:
                sys.exit("licenses/third-party.toml is out of date: run scripts/gen-licenses.py")
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
